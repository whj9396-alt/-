    public static function locale($locale = null)
    {
        if ($locale === null || $locale === '') {
            if (function_exists('determine_locale')) {
                $locale = determine_locale();
            } elseif (function_exists('get_locale')) {
                $locale = get_locale();
            } else {
                $locale = 'en_US';
            }
        }

        $language = strtolower(substr(str_replace('-', '_', (string) $locale), 0, 2));
        $supported = array('cs', 'de', 'en', 'es', 'fi', 'fr', 'hu', 'it', 'nl', 'pl', 'ro', 'sv', 'zh');

        return in_array($language, $supported, true) ? $language : 'en';
    }

    public static function t($key, $locale = null, array $values = array())
    {
        $translations = self::translations();
        $language = self::locale($locale);
        $text = isset($translations[$language][$key])
            ? $translations[$language][$key]
            : (isset($translations['en'][$key]) ? $translations['en'][$key] : (string) $key);

        if ($values !== array()) {
            $text = vsprintf($text, $values);
        }

        return (string) apply_filters('psdu_translation', $text, $key, $language);
    }

    public static function network_t($key, $network, $locale = null, array $values = array())
    {
        $network = PSDU_Utils::normalize_network($network);
        $text = self::t($key, $locale, $values);
        if ($network !== PSDU_Utils::NETWORK_ERC20) {
            return $text;
        }

        // Preserve the site's language while swapping only network-specific terms.
        $opposite_network = '__PSDU_OPPOSITE_NETWORK__';
        $text = str_replace('USDT-ERC20', $opposite_network, $text);
        $text = str_replace(
            array('USDT-TRC20', 'TRON', 'TRC20'),
            array('USDT-ERC20', 'Ethereum', 'ERC20'),
            $text
        );
        $text = str_replace($opposite_network, 'USDT-TRC20', $text);

        return (string) apply_filters('psdu_network_translation', $text, $key, $network, self::locale($locale));
    }

    public static function supported_languages()
    {
        return array('cs', 'de', 'en', 'es', 'fi', 'fr', 'hu', 'it', 'nl', 'pl', 'ro', 'sv', 'zh');
    }

